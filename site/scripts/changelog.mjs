#!/usr/bin/env node
// Generates the /docs/changelog page (en and es) from the GitHub releases of
// the repository. The release notes themselves are written by goreleaser from
// conventional commits (see the changelog block in ../.goreleaser.yaml), so
// nothing about the changelog is ever edited by hand.
//
// It runs before `next dev`, `next build` and `next typegen` (pnpm hooks) and
// by hand with `pnpm changelog`. It needs no secrets: the releases of a public
// repository are readable anonymously (GITHUB_TOKEN, when set, only raises the
// rate limit) and it never fails the build:
//
//   - no releases yet: the page says so and links to GitHub,
//   - GitHub unreachable: a previously generated page is kept, otherwise the
//     page falls back to a link to the GitHub releases.
//
// The generated files are gitignored (see ../.gitignore).
import { mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = "isaias-alt/vexillum";
const RELEASES_URL = `https://github.com/${REPO}/releases`;
const API_URL = `https://api.github.com/repos/${REPO}/releases?per_page=30`;
const FETCH_TIMEOUT_MS = 8000;

const NOTICE =
  "{/* Generated by site/scripts/changelog.mjs from the GitHub releases of " +
  REPO +
  ". Do not edit by hand: run `pnpm changelog` in site/. */}";

export const LOCALES = {
  en: {
    title: "Changelog",
    description: "What changed in each vexillum release, generated from the release notes.",
    intro:
      "What changed in each release, grouped into features, bug fixes and documentation. " +
      "This page is generated from the [GitHub releases](" + RELEASES_URL + "), whose notes are written from the commit history at release time.",
    empty: "There are no releases yet. The first one will show up here as soon as it is published.",
    unavailable: "The release notes could not be loaded when this site was built.",
    seeReleases: "See the releases on GitHub",
    released: "Released",
  },
  es: {
    title: "Registro de cambios",
    description: "Qué cambió en cada release de vexillum, generado a partir de las notas de release.",
    intro:
      "Qué cambió en cada release, agrupado en funcionalidades, correcciones y documentación. " +
      "Esta página se genera desde los [releases de GitHub](" + RELEASES_URL + "), cuyas notas se escriben desde el historial de commits al publicar. " +
      "Las notas se mantienen en inglés, igual que los mensajes de commit.",
    empty: "Todavía no hay releases. El primero aparecerá acá apenas se publique.",
    unavailable: "No se pudieron cargar las notas de release cuando se construyó este sitio.",
    seeReleases: "Ver los releases en GitHub",
    released: "Publicado",
  },
};

const yamlString = (s) => JSON.stringify(s);

/** Escapes text so MDX reads it literally: braces and `<` start expressions
 * and JSX. Code spans and fenced blocks are left alone, they are literal. */
export function escapeMDX(markdown) {
  let fenced = false;
  return markdown
    .split("\n")
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) {
        fenced = !fenced;
        return line;
      }
      if (fenced) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 === 1 ? part : part.replace(/[{}<]/g, "\\$&")))
        .join("");
    })
    .join("\n");
}

/** Turns one release body (goreleaser notes) into the markdown shown under the
 * release heading: drops goreleaser's own "## Changelog" title (the page has
 * its heading) and links each abbreviated commit hash. */
export function normalizeBody(body) {
  const lines = String(body ?? "")
    .replace(/\r\n/g, "\n")
    .trim()
    .split("\n");
  if (/^#{1,2}\s+Changelog\s*$/i.test(lines[0] ?? "")) lines.shift();
  const linked = lines.map((line) =>
    line.replace(
      /^(\s*[*-]\s+)([0-9a-f]{7,40})(\s)/,
      (_, lead, sha, trail) => `${lead}[${sha.slice(0, 7)}](https://github.com/${REPO}/commit/${sha})${trail}`,
    ),
  );
  return escapeMDX(linked.join("\n").trim());
}

const dateOf = (iso) => (typeof iso === "string" ? iso.slice(0, 10) : "");

function releaseSection(release, t) {
  const tag = release.tag_name;
  const url = release.html_url || `${RELEASES_URL}/tag/${tag}`;
  const date = dateOf(release.published_at || release.created_at);
  let out = `## [${tag}](${url})\n\n`;
  if (date) out += `${t.released} ${date}\n\n`;
  const body = normalizeBody(release.body);
  if (body) out += body + "\n";
  return out;
}

/** state is "ok" (releases is the list, possibly empty) or "unavailable". */
export function renderPage(lang, releases, state = "ok") {
  const t = LOCALES[lang];
  let out = "---\n";
  out += `title: ${yamlString(t.title)}\n`;
  out += `description: ${yamlString(t.description)}\n`;
  out += "---\n\n";
  out += NOTICE + "\n\n";
  out += t.intro + "\n\n";
  if (state === "unavailable") {
    out += `${t.unavailable} [${t.seeReleases}](${RELEASES_URL}).\n`;
  } else if (releases.length === 0) {
    out += `${t.empty} [${t.seeReleases}](${RELEASES_URL}).\n`;
  } else {
    out += releases.map((r) => releaseSection(r, t)).join("\n");
  }
  return out;
}

/** Published (non-draft) releases, newest first. Throws on any failure. */
export async function fetchReleases(fetchFn = fetch, env = process.env) {
  const headers = {
    Accept: "application/vnd.github+json",
    "User-Agent": "vexillum-site-changelog",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  if (env.GITHUB_TOKEN) headers.Authorization = `Bearer ${env.GITHUB_TOKEN}`;
  const res = await fetchFn(API_URL, { headers, signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
  if (!res.ok) throw new Error(`GitHub API answered ${res.status}`);
  const data = await res.json();
  if (!Array.isArray(data)) throw new Error("unexpected GitHub API response");
  return data
    .filter((r) => r && !r.draft && typeof r.tag_name === "string")
    .sort((a, b) => dateOf(b.published_at).localeCompare(dateOf(a.published_at)));
}

function writeAtomic(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.tmp-${process.pid}`;
  writeFileSync(tmp, content);
  renameSync(tmp, path);
}

const exists = (path) => {
  try {
    readFileSync(path);
    return true;
  } catch {
    return false;
  }
};

/** Writes both locales under contentDir. Never throws on a network problem. */
export async function generate(contentDir, fetchFn = fetch, log = console) {
  let releases = [];
  let state = "ok";
  try {
    releases = await fetchReleases(fetchFn);
  } catch (err) {
    state = "unavailable";
    log.warn(`changelog: could not load the releases (${err.message}); falling back`);
  }
  for (const lang of Object.keys(LOCALES)) {
    const path = join(contentDir, lang, "changelog.mdx");
    // Keep a page generated earlier rather than replace real notes with a
    // fallback because of a transient network failure.
    if (state === "unavailable" && exists(path)) continue;
    writeAtomic(path, renderPage(lang, releases, state));
  }
  log.log(`changelog: ${state === "ok" ? `${releases.length} release(s)` : "fallback page"}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const contentDir = join(dirname(fileURLToPath(import.meta.url)), "..", "content", "docs");
  generate(contentDir).catch((err) => {
    // Never fail the build over the changelog.
    console.warn(`changelog: ${err.message}`);
  });
}
